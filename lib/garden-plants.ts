export const PLANTS: Plant[] = Object.values(P)

/** Plant lookup by id. */
export function getPlant(id: string): Plant | undefined {
  return P[id]
}

/** Plants filtered by category. 'all' returns everything. */
export function getPlantsByCategory(category: string): Plant[] {
  if (category === 'all') return PLANTS
  return PLANTS.filter(p => p.category === category)
}

/** Search plants by name or scientific name (case-insensitive, accent-insensitive). */
export function searchPlants(query: string): Plant[] {
  const q = normalize(query)
  if (!q) return PLANTS
  return PLANTS.filter(p =>
    normalize(p.name).includes(q) || normalize(p.scientificName).includes(q)
  )
}

function normalize(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]/g, '')
}
